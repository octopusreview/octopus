import { mock } from 'bun:test';
import assert from 'node:assert/strict';
import { NextRequest } from 'next/server';
mock.module('server-only', () => ({}));
const events: Array<{ id: string }> = [];
const saved: Array<{ id: string }> = [];
mock.module('@/lib/pubby', () => ({ pubby: { trigger: async (_:string,event:string,data:unknown) => { if(event==='index-log') events.push(data as { id: string }); } } }));
mock.module('@/lib/elasticsearch', () => ({ writeSyncLog(entry: { id: string }) { saved.push(entry); }, deleteSyncLogs: async () => {} }));
mock.module('@/lib/indexing-abort', () => ({ createAbortController: () => new AbortController(), abortIndexing() {} }));
mock.module('@/lib/indexing-runner', () => ({ runIndexingInBackground: (...args:unknown[]) => { const log=args[6] as (s:string)=>void; log('synthetic-private-path synthetic-secret'); log('Processing local batch 1/2'); } }));
const repo = { id:'repo',fullName:'fixture/repo',provider:'github',defaultBranch:'main',installationId:1,indexStatus:'pending',indexAttemptId:null,updatedAt:new Date(),organizationId:'org',organization:{ githubInstallationId:1 } };
mock.module('@octopus/db', () => ({ prisma: { repository: { findUnique:async()=>repo,updateMany:async()=>({count:1}) } } }));
process.env.ADMIN_API_SECRET='synthetic-admin';
const { POST } = await import('@/app/api/admin/repositories/[id]/reindex/route');
const unauthorized=await POST(new NextRequest('http://localhost/api/admin/repositories/repo/reindex',{method:'POST'}),{params:Promise.resolve({id:'repo'})});
assert.equal(unauthorized.status,401);
assert.equal(events.length,0);
const response=await POST(new NextRequest('http://localhost/api/admin/repositories/repo/reindex',{method:'POST',headers:{authorization:'Bearer synthetic-admin'}}),{params:Promise.resolve({id:'repo'})});
assert.equal(response.status,200);
assert.equal(events.length, 2);
assert.deepEqual(events.map(event => event.id), saved.map(entry => entry.id));
assert.notEqual(events[0].id, events[1].id);
assert.doesNotMatch(JSON.stringify(events), /synthetic-private-path|synthetic-secret/);
assert.match(JSON.stringify(events), /Processing local batch 1\/2/);
